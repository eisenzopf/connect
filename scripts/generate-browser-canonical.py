#!/usr/bin/env python3
"""Freeze browser raw validation data from the current canonical contract.

No arbitrary schemas, remote references, configuration or network are accepted.
The prepared upstream copy and its actual registry must match the source contract.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/schemas/uctp-envelope-2.schema.json'
UPSTREAM = ROOT / '.deps/rvoip/crates/uctp/rvoip-uctp/src/v2'
OUTPUT = ROOT / 'sdk/typescript/src/browser_canonical_schema.ts'
VOCABULARY = {
    '$schema', '$id', '$defs', '$ref', 'title', 'description', 'type',
    'properties', 'required', 'additionalProperties', 'enum', 'const',
    'allOf', 'anyOf', 'oneOf', 'not', 'if', 'then', 'else', 'minLength',
    'maxLength', 'pattern', 'format', 'minimum', 'maximum', 'items',
    'minItems', 'maxItems', 'uniqueItems',
}


def generate():
    source = SOURCE.read_bytes()
    assert source == (UPSTREAM / 'envelope.schema.json').read_bytes(), 'Prepare matching upstream sources first'
    schema = json.loads(source)

    def check(node):
        assert isinstance(node, dict), 'Only fixed object schemas are supported'
        assert not set(node) - VOCABULARY, f'Unsupported schema vocabulary: {set(node) - VOCABULARY}'
        if '$ref' in node:
            assert node['$ref'].startswith('#/$defs/') and node['$ref'][8:] in schema['$defs']
        if 'pattern' in node:
            assert node['pattern'] in ('^[A-Za-z0-9._~-]+$', '^(sip|sips|tel):[!-~]+$')
        if 'format' in node:
            assert node['format'] == 'date-time'
        if 'type' in node:
            assert node['type'] in ('object', 'array', 'string', 'integer', 'number', 'boolean', 'null')
        if 'additionalProperties' in node:
            assert isinstance(node['additionalProperties'], bool)
        for name in ('minimum', 'maximum', 'minLength', 'maxLength', 'minItems', 'maxItems'):
            if name in node:
                assert isinstance(node[name], (int, float)) and abs(node[name]) <= 9007199254740991
        for name in ('$defs', 'properties'):
            for child in node.get(name, {}).values():
                check(child)
        for name in ('allOf', 'anyOf', 'oneOf'):
            for child in node.get(name, []):
                check(child)
        for name in ('items', 'not', 'if', 'then', 'else'):
            if name in node:
                check(node[name])

    check(schema)
    registry = []
    for branch in schema['allOf']:
        then = branch['then']
        if 'properties' not in then or 'payload' not in then['properties']:
            continue  # Additional journal-hint constraints remain in the full schema.
        required = then['required'] + then.get('anyOf', [{}])[0].get('required', [])
        registry.append([branch['if']['properties']['type']['const'], 'operation_id' in required, 'expected_revision' in required])
    actual = [[kind, operation == 'true', revision == 'true'] for kind, operation, revision in re.findall(
        r'\("([a-z.-]+)", (true|false), (true|false)\)',
        (UPSTREAM / 'payloads.rs').read_text().split('pub const REGISTRY:')[1])]
    assert sorted(actual) == sorted(registry)
    registry = actual
    assert len({row[0] for row in registry}) == len(registry)
    assert {row[0] for row in registry} == set(schema['properties']['type']['enum'])
    policy_source = ROOT / 'crates/connect-client/src/sdk/raw.rs'
    policy = policy_source.read_text().split('fn intent(')[1]
    read_match = re.search(r'let read = matches!\(\s*kind,(.*?)\);', policy, re.S)
    finite_match = re.search(r'if !matches!\(\s*kind,(.*?)\) \|\| kind', policy, re.S)
    assert read_match and finite_match, 'Review changed Rust raw classification'
    read_kinds = re.findall(r'"([a-z.-]+)"', read_match[1])
    finite_kinds = re.findall(r'"([a-z.-]+)"', finite_match[1])
    assert read_kinds and finite_kinds and set(read_kinds) <= set(finite_kinds)
    assert set(finite_kinds) <= {row[0] for row in registry}
    content = (
        '// Generated by scripts/generate-browser-canonical.py; do not edit.\n'
        f'// Frozen schema SHA-256: {hashlib.sha256(source).hexdigest()}\n'
        '// String storage keeps the parsed schema private to its fixed validator.\n'
        'export const FROZEN_ENVELOPE_SCHEMA_JSON: string = ' + json.dumps(json.dumps(schema, separators=(',', ':'), ensure_ascii=True)) + ';\n'
        'export const FROZEN_CANONICAL_REGISTRY: readonly (readonly [string, boolean, boolean])[] = Object.freeze(\n'
        + json.dumps(registry) + '.map(row => Object.freeze(row as [string, boolean, boolean])));\n'
        + '// Rust finite-request policy SHA-256: ' + hashlib.sha256(policy_source.read_bytes()).hexdigest() + '\n'
        + 'export const FROZEN_FINITE_KINDS: readonly string[] = Object.freeze(' + json.dumps(finite_kinds) + ');\n'
        + 'export const FROZEN_READ_KINDS: readonly string[] = Object.freeze(' + json.dumps(read_kinds) + ');\n'
    )
    formatted = subprocess.run(
        [str(ROOT / 'sdk/typescript/node_modules/.bin/prettier'), '--stdin-filepath', str(OUTPUT)],
        input=content, text=True, capture_output=True, check=True,
    ).stdout
    return formatted, len(registry)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count = generate()
    if args.check:
        assert OUTPUT.read_text() == content, 'Regenerate browser canonical schema data'
    else:
        OUTPUT.write_text(content)
    print(json.dumps({'check': args.check, 'types': count, 'schema_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest()}))
