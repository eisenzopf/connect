#!/usr/bin/env python3
"""Generate shared Rust payloads from the frozen schema into an upstream workspace.

The destination is explicit so generated .deps sources never become an
unrecorded source of truth. Review and record the resulting upstream patch.
"""
import argparse
import json
import pathlib
import re
import shutil

ROOT = pathlib.Path(__file__).resolve().parents[1]


def pascal(value):
    result = ''.join(s[:1].upper() + s[1:] for s in re.split(r'[^A-Za-z0-9]', value))
    return ('Value' + result) if result[:1].isdigit() else result


def generate(destination):
    schema = json.loads((ROOT / 'contracts/schemas/uctp-envelope-2.schema.json').read_text())
    definitions = schema['$defs']
    enums = {}

    # The runtime evaluates this fixed vocabulary. Refuse generation if a
    # future schema adds a constraint the shared decoder does not implement.
    vocabulary = {'$schema', '$id', '$defs', '$ref', 'title', 'description',
                  'type', 'properties', 'required', 'additionalProperties',
                  'enum', 'const', 'allOf', 'anyOf', 'oneOf', 'not', 'if', 'then',
                  'else', 'minLength', 'maxLength', 'pattern', 'format',
                  'minimum', 'maximum', 'items', 'minItems', 'maxItems', 'uniqueItems'}

    def check_vocabulary(node):
        if not isinstance(node, dict):
            return
        unknown = set(node) - vocabulary
        if unknown:
            raise ValueError(f'Unsupported compiled schema vocabulary: {unknown}')
        if node.get('additionalProperties', True) is not True:
            raise ValueError('Runtime currently preserves optional extensions')
        if 'pattern' in node and node['pattern'] != '^[A-Za-z0-9._~-]+$':
            raise ValueError('Runtime supports only the identifier pattern')
        if 'format' in node and node['format'] != 'date-time':
            raise ValueError('Unsupported format')
        for key in ('$defs', 'properties'):
            for child in node.get(key, {}).values():
                check_vocabulary(child)
        for key in ('allOf', 'anyOf', 'oneOf'):
            for child in node.get(key, []):
                check_vocabulary(child)
        for key in ('items', 'not', 'if', 'then', 'else'):
            if key in node:
                check_vocabulary(node[key])

    check_vocabulary(schema)

    def field_type(spec, hint):
        if hint == 'MessageSendTo':
            return 'MessageAudience'
        if '$ref' in spec:
            return spec['$ref'].rsplit('/', 1)[-1]
        if 'anyOf' in spec:
            return field_type(spec['anyOf'][0], hint)
        if 'enum' in spec and all(isinstance(x, str) for x in spec['enum']):
            enums[hint] = spec['enum']
            return hint
        if 'const' in spec:
            enums[hint] = [spec['const']]
            return hint
        kind = spec.get('type')
        if kind == 'string':
            return 'DateTime<Utc>' if spec.get('format') == 'date-time' else 'String'
        if kind == 'integer':
            return 'u64'
        if kind == 'number':
            return 'f64'
        if kind == 'boolean':
            return 'bool'
        if kind == 'array':
            return 'Vec<' + field_type(spec['items'], hint + 'Item') + '>'
        return 'Value'

    lines = ['// Generated by Connect scripts/generate-gate6-rust.py; do not edit.',
             'use chrono::{DateTime, Utc};', 'use serde::{Deserialize, Serialize};',
             'use serde_json::Value;', 'use super::Identifier;', '']
    lines.extend(['/// Explicit broadcast or a nonempty checked participant set.',
                  '#[derive(Clone, Serialize, Deserialize)]', '#[serde(untagged)]',
                  'pub enum MessageAudience { All(Broadcast), Participants(Vec<Identifier>) }',
                  'impl std::fmt::Debug for MessageAudience {',
                  '    fn fmt(&self, f: &mut std::fmt::Formatter<\'_>) -> std::fmt::Result { f.write_str("MessageAudience(redacted)") }',
                  '}',
                  '#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]',
                  'pub enum Broadcast { #[serde(rename = "all")] All }', ''])
    for name, spec in definitions.items():
        if name == 'Identifier':
            continue
        if 'enum' in spec:
            enums[name] = spec['enum']
            continue
        if name == 'SessionUpdate':
            # The details object is structurally typed by the discriminant,
            # rather than leaving application code to interpret arbitrary JSON.
            lines.extend(['#[derive(Clone, Serialize, Deserialize)]',
                          '#[serde(tag = "kind", content = "details")]',
                          'pub enum SessionUpdate {',
                          '    #[serde(rename = "participant-leave")]',
                          '    ParticipantLeave { participant_id: Identifier },',
                          '    #[serde(rename = "role-change")]',
                          '    RoleChange { participant_id: Identifier, role: String },',
                          '    #[serde(rename = "medium-upgrade")]',
                          '    MediumUpgrade { media: Vec<StreamInfoKind> },',
                          '    #[serde(rename = "codec-renegotiate")]',
                          '    CodecRenegotiate { codec_preferences: Vec<String> },',
                          '}', ''])
        else:
            lines.extend(['#[derive(Clone, Serialize, Deserialize)]', f'pub struct {name} {{'])
            for key, value in spec.get('properties', {}).items():
                rust = field_type(value, name + pascal(key))
                optional = key not in spec.get('required', [])
                if optional:
                    lines.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
                    rust = 'Option<' + rust + '>'
                field = 'r#' + key if key in ('type', 'from', 'ref') else key
                lines.append(f'    pub {field}: {rust},')
            lines.extend(['}', ''])
        # Message contents, addresses, credentials and private audiences must
        # never leak through incidental logging of typed structs.
        lines.extend([f'impl std::fmt::Debug for {name} {{',
                      '    fn fmt(&self, f: &mut std::fmt::Formatter<\'_>) -> std::fmt::Result {',
                      f'        f.write_str("{name}(redacted)")', '    }', '}', ''])
    for name, values in enums.items():
        lines.extend(['#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]', f'pub enum {name} {{'])
        for value in values:
            lines.extend([f'    #[serde(rename = {json.dumps(value)})]', f'    {pascal(value)},'])
        lines.extend(['}', ''])

    registry = []
    for branch in schema['allOf']:
        kind = branch['if']['properties']['type']['const']
        then = branch['then']
        model = then['properties']['payload']['$ref'].rsplit('/', 1)[-1]
        registry.append((kind, model, then['required']))
    lines.extend(['/// Checked typed wire payloads. Unknown optional fields are ignored for execution.',
                  '#[derive(Debug, Clone, Serialize, Deserialize)]',
                  '#[serde(tag = "type", content = "payload")]', 'pub enum Payload {'])
    for kind, model, _ in registry:
        lines.extend([f'    #[serde(rename = {json.dumps(kind)})]', f'    {pascal(kind)}({model}),'])
    lines.extend(['}', '', 'impl Payload {', '    pub fn kind(&self) -> &\'static str {', '        match self {'])
    for kind, _, _ in registry:
        lines.append(f'            Self::{pascal(kind)}(_) => {json.dumps(kind)},')
    lines.extend(['        }', '    }', '}', '', '/// (wire kind, operation ID required, expected revision required).',
                  'pub const REGISTRY: &[(&str, bool, bool)] = &['])
    for kind, _, required in registry:
        lines.append(f'    ({json.dumps(kind)}, {str("operation_id" in required).lower()}, {str("expected_revision" in required).lower()}),')
    lines.extend(['];', ''])
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'payloads.rs').write_text('\n'.join(lines))
    shutil.copyfile(ROOT / 'contracts/schemas/uctp-envelope-2.schema.json', destination / 'envelope.schema.json')
    shutil.copyfile(ROOT / 'contracts/uctp-vectors/gate6-envelope.json', destination / 'golden-vectors.json')
    print(json.dumps({'types': len(registry), 'destination': str(destination)}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', type=pathlib.Path)
    generate(parser.parse_args().destination)
