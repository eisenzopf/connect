//! Historical native sequence membership, never a transmission or permission grant.
use crate::{Error, Result};
use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;
pub const PROFILE: &str = "connect/native-public-sequence-cut/1";
pub const CURSOR_PROFILE: &str = "native-sequence-cursor/1";
pub const MAX_ORDINAL: u64 = 9_007_199_254_740_991;
fn invalid() -> Error {
    Error::new("bad-parameters", "Invalid native activation boundary")
}
fn id(v: &str) -> bool {
    !v.is_empty() && v.len() <= 256 && !v.chars().any(char::is_control)
}
fn incarnation(v: &str) -> bool {
    v.len() == 32
        && v.bytes()
            .all(|c| c.is_ascii_digit() || (b'a'..=b'f').contains(&c))
        && v.bytes().any(|c| c != b'0')
}
/// Generated by the original native writer and carried identically on both
/// signed negotiation legs. It is not supplied by the peer's media offer.
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativeEgressIdentity {
    pub profile: String,
    pub physical_incarnation: String,
    pub stream_generation: u64,
    pub connection_generation: u64,
    pub initial_outer_sequence: u32,
}
impl NativeEgressIdentity {
    pub fn validate(&self) -> Result<()> {
        if self.profile != CURSOR_PROFILE
            || !incarnation(&self.physical_incarnation)
            || !(1..=MAX_ORDINAL).contains(&self.stream_generation)
            || !(1..=MAX_ORDINAL).contains(&self.connection_generation)
            || self.initial_outer_sequence != 0
        {
            return Err(invalid());
        }
        Ok(())
    }
}
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativeSequenceCut {
    pub stream_id: String,
    pub stream_local_id: u16,
    pub stream_generation: u64,
    pub physical_incarnation: String,
    pub sequence_space: String,
    pub public_sequence_floor: u32,
    pub cursor_ordinal: u64,
    pub submission_observed: bool,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SequenceMembership {
    Private,
    Public,
}
impl NativeSequenceCut {
    pub fn validate(&self) -> Result<()> {
        if self.stream_local_id == 0
            || !id(&self.stream_id)
            || !incarnation(&self.physical_incarnation)
            || !(1..=MAX_ORDINAL).contains(&self.stream_generation)
            || self.sequence_space != "native-outer-u32"
            || self.cursor_ordinal >= 0x8000_0000
            || self.public_sequence_floor != self.cursor_ordinal as u32
            || self.submission_observed
        {
            return Err(invalid());
        }
        Ok(())
    }
    pub fn matches(
        &self,
        stream_id: &str,
        handle: u16,
        identity: &NativeEgressIdentity,
        generation: u64,
    ) -> Result<()> {
        self.validate()?;
        identity.validate()?;
        if self.stream_id != stream_id
            || self.stream_local_id != handle
            || self.stream_generation != identity.stream_generation
            || self.physical_incarnation != identity.physical_incarnation
            || generation != identity.connection_generation
        {
            return Err(invalid());
        }
        Ok(())
    }
    /// Caller retains original datagrams from this exact signed physical reader
    /// in a bounded interval shorter than half the native sequence space.
    /// RTP/RTCP failures may leave gaps; those gaps are never output observations.
    pub fn membership(&self, sequence: u32) -> Result<SequenceMembership> {
        self.validate()?;
        // The signed original cursor starts at zero. Neither a late wrap nor a
        // half-range ambiguity is silently rebased into this historical cut.
        if sequence >= 0x8000_0000 {
            return Err(invalid());
        }
        Ok(if sequence >= self.public_sequence_floor {
            SequenceMembership::Public
        } else {
            SequenceMembership::Private
        })
    }
}
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "scope", rename_all = "kebab-case", deny_unknown_fields)]
pub enum NativeActivationAudience {
    Public { streams: Vec<NativeSequenceCut> },
    PrivateConsultation { original_operation: String },
    Unsupported { reason: String },
}
#[cfg_attr(feature = "schema", derive(schemars::JsonSchema))]
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct NativeActivationBoundary {
    pub profile: String,
    pub operation_record_id: String,
    pub operation_id: String,
    pub source_connection_id: String,
    pub target_connection_id: String,
    pub target_generation: u64,
    pub stream_revision: u64,
    pub audience: NativeActivationAudience,
}
impl NativeActivationBoundary {
    pub fn validate(&self) -> Result<()> {
        if self.profile != PROFILE
            || ![
                &self.operation_record_id,
                &self.operation_id,
                &self.source_connection_id,
                &self.target_connection_id,
            ]
            .into_iter()
            .all(|s| id(s))
            || self.source_connection_id == self.target_connection_id
            || !(1..=MAX_ORDINAL).contains(&self.target_generation)
            || !(3..=MAX_ORDINAL).contains(&self.stream_revision)
        {
            return Err(invalid());
        }
        match &self.audience {
            NativeActivationAudience::Public { streams } => {
                if streams.is_empty() || streams.len() > 32 {
                    return Err(invalid());
                }
                let (mut ids, mut handles, mut physical) =
                    (BTreeSet::new(), BTreeSet::new(), BTreeSet::new());
                for s in streams {
                    s.validate()?;
                    if !ids.insert(&s.stream_id)
                        || !handles.insert(s.stream_local_id)
                        || !physical.insert(&s.physical_incarnation)
                    {
                        return Err(invalid());
                    }
                }
            }
            NativeActivationAudience::PrivateConsultation { original_operation }
                if id(original_operation) => {}
            NativeActivationAudience::Unsupported { reason } if reason == "non-native-adapter" => {}
            _ => return Err(invalid()),
        }
        Ok(())
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    fn cut() -> NativeSequenceCut {
        NativeSequenceCut {
            stream_id: "audio".into(),
            stream_local_id: 1,
            stream_generation: 1,
            physical_incarnation: "00000000000000000000000000000001".into(),
            sequence_space: "native-outer-u32".into(),
            public_sequence_floor: 4,
            cursor_ordinal: 4,
            submission_observed: false,
        }
    }
    #[test]
    fn activation_cut_wrap_and_failed_reservations_are_not_io() {
        let c = cut();
        assert!(c.membership(u32::MAX).is_err());
        assert_eq!(c.membership(0).unwrap(), SequenceMembership::Private);
        assert_eq!(c.membership(4).unwrap(), SequenceMembership::Public);
        let mut wrapped = c.clone();
        wrapped.cursor_ordinal = 1u64 << 32;
        wrapped.public_sequence_floor = 0;
        assert!(wrapped.validate().is_err());
        assert!(c.membership(1u32 << 31).is_err());
        assert!(!c.submission_observed);
    }
    #[test]
    fn activation_cut_strict_fields_incarnation_and_floor() {
        let mut c = cut();
        c.cursor_ordinal += 1;
        assert!(c.validate().is_err());
        c = cut();
        c.submission_observed = true;
        assert!(c.validate().is_err());
        let mut v = serde_json::to_value(cut()).unwrap();
        v["transmitted"] = true.into();
        assert!(serde_json::from_value::<NativeSequenceCut>(v).is_err());
        let i = NativeEgressIdentity {
            profile: CURSOR_PROFILE.into(),
            physical_incarnation: "00000000000000000000000000000002".into(),
            stream_generation: 1,
            connection_generation: 2,
            initial_outer_sequence: 0,
        };
        assert!(cut().matches("audio", 1, &i, 2).is_err());
    }
    #[test]
    fn private_successor_cannot_claim_public_streams() {
        let v = serde_json::json!({"scope":"private-consultation","original_operation":"original","streams":[cut()]});
        assert!(serde_json::from_value::<NativeActivationAudience>(v).is_err());
    }
}
